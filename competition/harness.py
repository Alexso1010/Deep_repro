"""
Competition harness for the ETTh1 forecasting task: data, training loop, evaluation and MLflow logging.

DO NOT EDIT THIS FILE. Everything a participant can change goes through train_competition.py
(the models) and the hydra configs (conf/competition.yaml and its defaults).
The SHA-256 of this file, of the data object and of the dataset are logged as tags on every run:
runs whose hashes differ from the reference ones are excluded from the leaderboard.
"""

import hashlib
import inspect
import os
from typing import cast

import matplotlib.pyplot as plt
import mlflow
import numpy as np
import torch
from hydra.utils import instantiate
from omegaconf import DictConfig, OmegaConf
from torch import nn

from dataops.dataobject import TSDataObject

EXPERIMENT_NAME = "etth1_competition"
DATA_PATH = "data/etth1.pkl"
TARGET = "OT"
HORIZON = 96


###############################################################################
#                                  HELPERS                                    #
###############################################################################


def _sha256(path: str) -> str:
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def _flatten(d: dict, prefix: str = "") -> dict:
    flat = {}
    for key, value in d.items():
        name = f"{prefix}{key}"
        if isinstance(value, dict):
            flat.update(_flatten(value, prefix=f"{name}."))
        else:
            flat[name] = value
    return flat


def build_model(cfg: DictConfig, data_object: TSDataObject) -> nn.Module:
    """
    Instantiate the participant's model. The task dimensions are injected by the harness,
    so every model receives `lookback`, `n_channels`, `horizon` and `target_idx` as keyword arguments.
    """
    model = instantiate(
        cfg.model.model,
        lookback=data_object.lookback,
        n_channels=data_object.n_channels,
        horizon=HORIZON,
        target_idx=data_object.target_idx,
    )
    X, _ = next(iter(data_object.val_dl))
    with torch.no_grad():
        out = model(X)
    expected = (X.shape[0], HORIZON)
    if tuple(out.shape) != expected:
        raise ValueError(
            f"The model must map (batch, lookback, n_channels) = {tuple(X.shape)} "
            f"to (batch, horizon) = {expected}, got {tuple(out.shape)}"
        )
    return model


@torch.no_grad()
def evaluate(model: nn.Module, dataloader) -> tuple[float, float]:
    """
    MSE and MAE averaged over every window and every forecast step.
    """
    model.eval()
    squared_error, absolute_error, n = 0.0, 0.0, 0
    for X_batch, y_batch in dataloader:
        error = model(X_batch) - y_batch
        squared_error += (error**2).sum().item()
        absolute_error += error.abs().sum().item()
        n += y_batch.numel()
    return squared_error / n, absolute_error / n


@torch.no_grad()
def plot_forecasts(model: nn.Module, data_object: TSDataObject, n_examples: int = 4):
    """Plot a few test forecasts in degrees Celsius, evenly spread over the test period."""
    model.eval()
    mean = data_object.mean[data_object.target_idx]
    std = data_object.std[data_object.target_idx]
    idxs = np.linspace(0, len(data_object.test_ds) - 1, n_examples).astype(int)
    fig, axes = plt.subplots(n_examples, 1, figsize=(10, 2.5 * n_examples))
    for ax, idx in zip(axes, idxs):
        X, y = data_object.test_ds[idx]
        y_hat = model(X.unsqueeze(0))[0]
        history = X[:, data_object.target_idx].numpy() * std + mean
        t_history = np.arange(-len(history), 0)
        t_future = np.arange(HORIZON)
        ax.plot(t_history, history, color="grey", label="history")
        ax.plot(t_future, y.numpy() * std + mean, color="black", label="truth")
        ax.plot(t_future, y_hat.numpy() * std + mean, color="tab:blue", label="forecast")
        ax.set_ylabel("OT (°C)")
    axes[0].legend(loc="upper left")
    axes[-1].set_xlabel("hours from forecast origin")
    fig.tight_layout()
    return fig


###############################################################################
#                                  TRAINER                                    #
###############################################################################


def train(
    model: nn.Module,
    data_object: TSDataObject,
    cfg: DictConfig,
    checkpoint_dir: str,
) -> float:
    optimizer = instantiate(cfg.training.optimizer, params=model.parameters())
    criterion = instantiate(cfg.training.criterion)
    scheduler = (
        instantiate(cfg.training.scheduler, optimizer=optimizer)
        if cfg.training.scheduler is not None
        else None
    )
    best_path = os.path.join(checkpoint_dir, "best_checkpoint.pt")
    best_mse = float("inf")
    epochs_without_improvement = 0

    for epoch in range(cfg.training.epochs):
        model.train()
        running_loss = 0.0
        for X_batch, y_batch in data_object.train_dl:
            optimizer.zero_grad()
            loss = criterion(model(X_batch), y_batch)
            loss.backward()
            if cfg.training.grad_clip is not None:
                nn.utils.clip_grad_norm_(model.parameters(), cfg.training.grad_clip)
            optimizer.step()
            running_loss += loss.item()
        if scheduler is not None:
            scheduler.step()

        val_mse, val_mae = evaluate(model, data_object.val_dl)
        mlflow.log_metrics(
            {
                "train/loss": running_loss / len(data_object.train_dl),
                "val/mse": val_mse,
                "val/mae": val_mae,
            },
            step=epoch,
        )
        print(f"epoch {epoch + 1:3d} | val mse {val_mse:.4f} | val mae {val_mae:.4f}")

        if val_mse < best_mse:
            best_mse = val_mse
            epochs_without_improvement = 0
            torch.save(model.state_dict(), best_path)
        else:
            epochs_without_improvement += 1
            if epochs_without_improvement >= cfg.training.patience:
                print(f"Early stopping at epoch {epoch + 1}")
                break

    mlflow.log_artifact(best_path, artifact_path="checkpoints")
    return best_mse


###############################################################################
#                               ENTRY POINT                                   #
###############################################################################


def run_competition(cfg: DictConfig) -> float:
    """Train the configured model, evaluate its best checkpoint on the test set and log everything."""
    if OmegaConf.is_missing(cfg, "participant"):
        raise ValueError("Set your leaderboard name: uv run train_competition.py participant=<your_name>")
    torch.manual_seed(cfg.seed)

    data_object = TSDataObject(
        data_path=DATA_PATH,
        lookback=cfg.data.lookback,
        horizon=HORIZON,
        target=TARGET,
        batch_size=cfg.training.batch_size,
    )
    data_object.make_datasets()
    data_object.make_dataloaders()

    model = build_model(cfg, data_object)
    n_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(f"{type(model).__name__}: {n_params} trainable parameters")

    mlflow.set_tracking_uri("https://mlflow-iodaa.allynd.re/")
    mlflow.set_experiment(EXPERIMENT_NAME)

    with mlflow.start_run() as run:
        checkpoint_dir = os.path.join(cfg.checkpoints_dir, run.info.run_id)
        os.makedirs(checkpoint_dir, exist_ok=True)

        mlflow.set_tags(
            {
                "participant": cfg.participant,
                "model_class": type(model).__name__,
                "integrity/harness_sha256": _sha256(os.path.abspath(__file__)),
                "integrity/dataobject_sha256": _sha256(cast(str, inspect.getsourcefile(TSDataObject))),
                "integrity/data_sha256": _sha256(DATA_PATH),
            }
        )
        mlflow.log_params(_flatten(cast(dict, OmegaConf.to_container(cfg, resolve=True))))
        mlflow.log_param("n_params", n_params)
        mlflow.log_text(OmegaConf.to_yaml(cfg), "config_exp.yaml")
        # Log the source file defining the model, so that every leaderboard entry is reproducible
        mlflow.log_artifact(cast(str, inspect.getsourcefile(type(model))), artifact_path="code")

        best_val_mse = train(model, data_object, cfg, checkpoint_dir)

        model.load_state_dict(
            torch.load(os.path.join(checkpoint_dir, "best_checkpoint.pt"), weights_only=True)
        )
        best_val_mse, best_val_mae = evaluate(model, data_object.val_dl)
        test_mse, test_mae = evaluate(model, data_object.test_dl)
        target_std = float(data_object.std[data_object.target_idx])
        mlflow.log_metrics(
            {
                "val/best_mse": best_val_mse,
                "val/best_mae": best_val_mae,
                "test/mse": test_mse,
                "test/mae": test_mae,
                "test/mae_celsius": test_mae * target_std,
            }
        )
        fig = plot_forecasts(model, data_object)
        mlflow.log_figure(fig, "test_forecasts.png")
        plt.close(fig)

        print(f"Best val MSE: {best_val_mse:.4f}")
        print(f"Test MSE: {test_mse:.4f} | Test MAE: {test_mae:.4f} ({test_mae * target_std:.2f} °C)")

    # Returned value is minimized by Optuna (direction=minimize in an hpo config)
    return best_val_mse
